func sampleSavedQuery(name, consoleType, connectionID string) *model.SavedQuery {
	return &model.SavedQuery{
		Name:         name,
		ConsoleType:  consoleType,
		ConnectionID: connectionID,
		Content:      "SELECT 1",
	}
}

func TestStoreSavedQueryCreateAssignsIDAndTimestamps(t *testing.T) {
	s := newTestStore(t)
	q := sampleSavedQuery("每日消费延迟", "kafka-sql", "conn-1")
	if err := s.CreateSavedQuery(q); err != nil {
		t.Fatalf("CreateSavedQuery failed: %v", err)
	}
	if q.ID == "" {
		t.Fatal("id must be generated by the store")
	}
	if q.CreatedAt == 0 || q.UpdatedAt == 0 {
		t.Fatal("timestamps must be set")
	}
	if q.CreatedAt != q.UpdatedAt {
		t.Fatalf("create must set identical timestamps, got %d/%d", q.CreatedAt, q.UpdatedAt)
	}
	got, err := s.GetSavedQuery(q.ID)
	if err != nil {
		t.Fatalf("GetSavedQuery failed: %v", err)
	}
	if got.Name != "每日消费延迟" || got.ConsoleType != "kafka-sql" || got.ConnectionID != "conn-1" {
		t.Fatalf("fields not round-tripped: %+v", got)
	}
	if got.Content != "SELECT 1" {
		t.Fatalf("content not round-tripped: %q", got.Content)
	}
	if got.CreatedAt != q.CreatedAt || got.UpdatedAt != q.UpdatedAt {
		t.Fatalf("timestamps not persisted: got %d/%d want %d/%d", got.CreatedAt, got.UpdatedAt, q.CreatedAt, q.UpdatedAt)
	}
}

func TestStoreSavedQueryCreateDuplicateName(t *testing.T) {
	s := newTestStore(t)
	first := sampleSavedQuery("同名", "kafka-sql", "conn-1")
	if err := s.CreateSavedQuery(first); err != nil {
		t.Fatalf("create first failed: %v", err)
	}
	// 同 (console_type, connection_id) 下重名必须报中文错误。
	dup := sampleSavedQuery("同名", "kafka-sql", "conn-1")
	err := s.CreateSavedQuery(dup)
	if err == nil {
		t.Fatal("duplicate name in the same scope must fail")
	}
	if !strings.Contains(err.Error(), "同名查询已存在") {
		t.Fatalf("expected Chinese duplicate error, got %q", err.Error())
	}
	if dup.ID != "" {
		t.Fatalf("failed create must not assign an id, got %q", dup.ID)
	}
	// 同名但不同连接:允许。
	if err := s.CreateSavedQuery(sampleSavedQuery("同名", "kafka-sql", "conn-2")); err != nil {
		t.Fatalf("same name on another connection must be allowed: %v", err)
	}
	// 同名但不同控制台:允许。
	if err := s.CreateSavedQuery(sampleSavedQuery("同名", "ch-sql", "conn-1")); err != nil {
		t.Fatalf("same name on another console must be allowed: %v", err)
	}
}

func TestStoreSavedQueryUpdateAppliesAndRefreshesUpdatedAt(t *testing.T) {
	s := newTestStore(t)
	q := sampleSavedQuery("原名", "kafka-sql", "conn-1")
	if err := s.CreateSavedQuery(q); err != nil {
		t.Fatalf("create failed: %v", err)
	}
	createdAt, updatedAt := q.CreatedAt, q.UpdatedAt
	time.Sleep(2 * time.Millisecond) // 保证 updated_at 单调递增(UnixMilli 粒度)
	q.Name = "新名"
	q.Content = "SELECT 2"
	if err := s.UpdateSavedQuery(q); err != nil {
		t.Fatalf("update failed: %v", err)
	}
	if q.CreatedAt != createdAt {
		t.Fatalf("created_at must not change on update: got %d want %d", q.CreatedAt, createdAt)
	}
	if q.UpdatedAt <= updatedAt {
		t.Fatalf("updated_at must be refreshed on update: got %d <= %d", q.UpdatedAt, updatedAt)
	}
	got, err := s.GetSavedQuery(q.ID)
	if err != nil {
		t.Fatalf("get after update failed: %v", err)
	}
	if got.Name != "新名" || got.Content != "SELECT 2" {
		t.Fatalf("update not applied: %+v", got)
	}
	if got.ConsoleType != "kafka-sql" || got.ConnectionID != "conn-1" {
		t.Fatalf("update must not touch console_type/connection_id: %+v", got)
	}
	if got.UpdatedAt != q.UpdatedAt {
		t.Fatalf("refreshed updated_at not persisted: got %d want %d", got.UpdatedAt, q.UpdatedAt)
	}
}

func TestStoreSavedQueryUpdateDuplicateNameExcludesSelf(t *testing.T) {
	s := newTestStore(t)
	a := sampleSavedQuery("甲", "kafka-sql", "conn-1")
	b := sampleSavedQuery("乙", "kafka-sql", "conn-1")
	for _, q := range []*model.SavedQuery{a, b} {
		if err := s.CreateSavedQuery(q); err != nil {
			t.Fatalf("create failed: %v", err)
		}
	}
	// 改成别人的名字:拒绝。
	a.Name = "乙"
	err := s.UpdateSavedQuery(a)
	if err == nil {
		t.Fatal("renaming onto another query's name must fail")
	}
	if !strings.Contains(err.Error(), "同名查询已存在") {
		t.Fatalf("expected Chinese duplicate error, got %q", err.Error())
	}
	// 名字保持不变(排除自身):允许。
	a.Name = "甲"
	if err := s.UpdateSavedQuery(a); err != nil {
		t.Fatalf("keeping one's own name must be allowed: %v", err)
	}
}

