func TestStoreSavedQueryListFilterCombinations(t *testing.T) {
	s := newTestStore(t)
	qa := sampleSavedQuery("A", "kafka-sql", "conn-1")
	qb := sampleSavedQuery("B", "kafka-sql", "conn-2")
	qc := sampleSavedQuery("C", "ch-sql", "conn-1")
	for _, q := range []*model.SavedQuery{qa, qb, qc} {
		if err := s.CreateSavedQuery(q); err != nil {
			t.Fatalf("create %s failed: %v", q.Name, err)
		}
	}
	all, err := s.ListSavedQueries("", "")
	if err != nil {
		t.Fatalf("list all failed: %v", err)
	}
	if len(all) != 3 {
		t.Fatalf("expected 3 saved queries, got %d", len(all))
	}
	byConsole, err := s.ListSavedQueries("kafka-sql", "")
	if err != nil {
		t.Fatalf("list by console failed: %v", err)
	}
	if len(byConsole) != 2 {
		t.Fatalf("expected 2 kafka-sql queries, got %d", len(byConsole))
	}
	byConn, err := s.ListSavedQueries("", "conn-1")
	if err != nil {
		t.Fatalf("list by connection failed: %v", err)
	}
	if len(byConn) != 2 {
		t.Fatalf("expected 2 queries for conn-1, got %d", len(byConn))
	}
	both, err := s.ListSavedQueries("kafka-sql", "conn-1")
	if err != nil {
		t.Fatalf("list by console+connection failed: %v", err)
	}
	if len(both) != 1 || both[0].Name != "A" {
		t.Fatalf("expected only A for (kafka-sql, conn-1), got %+v", both)
	}
	none, err := s.ListSavedQueries("mysql-sql", "conn-9")
	if err != nil {
		t.Fatalf("list empty scope failed: %v", err)
	}
	if none == nil || len(none) != 0 {
		t.Fatalf("empty result must be a non-nil empty slice, got %+v", none)
	}
}

func TestStoreSavedQueryListOrdersByUpdatedAtDesc(t *testing.T) {
	s := newTestStore(t)
	q1 := sampleSavedQuery("最早", "kafka-sql", "conn-1")
	if err := s.CreateSavedQuery(q1); err != nil {
		t.Fatalf("create q1 failed: %v", err)
	}
	time.Sleep(2 * time.Millisecond)
	q2 := sampleSavedQuery("居中", "kafka-sql", "conn-1")
	if err := s.CreateSavedQuery(q2); err != nil {
		t.Fatalf("create q2 failed: %v", err)
	}
	time.Sleep(2 * time.Millisecond)
	q3 := sampleSavedQuery("最新", "kafka-sql", "conn-1")
	if err := s.CreateSavedQuery(q3); err != nil {
		t.Fatalf("create q3 failed: %v", err)
	}
	names := func(list []*model.SavedQuery) []string {
		out := make([]string, 0, len(list))
		for _, q := range list {
			out = append(out, q.Name)
		}
		return out
	}
	if got := names(mustListSavedQueries(t, s, "kafka-sql", "conn-1")); got[0] != "最新" || got[1] != "居中" || got[2] != "最早" {
		t.Fatalf("expected newest-first order, got %v", got)
	}
	// 更新最早的条目后,它应排到最前。
	time.Sleep(2 * time.Millisecond)
	q1.Content = "SELECT 42"
	if err := s.UpdateSavedQuery(q1); err != nil {
		t.Fatalf("update q1 failed: %v", err)
	}
	if got := names(mustListSavedQueries(t, s, "kafka-sql", "conn-1")); got[0] != "最早" {
		t.Fatalf("updated entry must sort first, got %v", got)
	}
}

func mustListSavedQueries(t *testing.T, s *Store, consoleType, connectionID string) []*model.SavedQuery {
	t.Helper()
	list, err := s.ListSavedQueries(consoleType, connectionID)
	if err != nil {
		t.Fatalf("ListSavedQueries failed: %v", err)
	}
	return list
}
